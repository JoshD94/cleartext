"""ClearText's default pipeline (on by default since November 23, 2026).

  1. F2, the safe split: T5 + dependency compound splitter, authored phrases,
     the 0.5 passage entailment floor (`F2` below; generated by
     `ensemble_study`/`param_sweeps` like every finalist).
  2. Structure v3 (`structure_v2.KEPT_V3`): by-phrase passive -> active
     (passive_v5), "we" recovery (passive_recovered), appositive extraction
     (appositive_v4) and fronted-clause split, each behind F2's hard checks
     and the 0.5 entailment floor (cross-encoder/nli-deberta-v3-small).
  3. The learned word stage, arm p50 (round 19's frozen filter at its
     pre-committed threshold), at most one swap per sentence and three per
     passage.

Each stage passed its own pre-registered blind rating on fresh text
(models/docs/DEFAULT_PIPELINE.md). No LLM is used.

Subcommands (raw text and outputs stay in --state, outside the checkout):
  run     apply stages 2-3 to F2 outputs: --f2 FILE ({id: F2 output}) -> --out FILE
  dev     stages 2-3 on F2's cached test-set-v3 dev outputs (checkpointed per passage),
          written as structure_v2 dev arms `default` and `f2_words`; then
          `structure_v2 score/judge --arms combo-v3 f2_words default`
  check   regression: recompute p50 on round 26 passages and compare with
          round 26's recorded picks
"""

import argparse
import json
import pickle
import time
from pathlib import Path

from . import structure_v2 as SV
from .learned_words import STATE as WORD_STATE
from .learned_words import read_jsonl

F2 = SV.F2
STRUCTURE_OPS = ("passive_v5", "passive_recovered", "appositive_v4", "fronted_split")  # KEPT_V3
MIN_ENTAILMENT = 0.5
WORDS_ARM = "p50"


class WordsP50:
    """The learned word stage, arm p50, on one passage (rounds 19-26 apply path)."""

    def __init__(self, threads=4):
        import torch

        from cleartext.learned_words import senses as SN

        from . import learned_words_r9 as R
        from . import learned_words_r19 as P19
        from . import learned_words_stacker as S
        from .learned_words_rewrite import load
        from .learned_words_simpler import SIMPLER

        torch.set_num_threads(threads)
        pre = json.load(open(P19.PRECOMMIT))
        if SV.sha(P19.MODEL) != pre["model_sha256"]:
            raise SystemExit("REFUSED: p50 model differs from the round-19 pre-commitment")
        self.threshold = pre["thresholds"][WORDS_ARM]
        self.p50 = pickle.load(open(P19.MODEL, "rb"))
        self.clf_s, _ = S.load_filter()
        self.sn = SN.load(R.TABLE)
        _, self.T, self.ids, _ = load()
        self.model = pickle.load(open(WORD_STATE / "model.pkl", "rb"))
        self.simpler = pickle.load(open(SIMPLER, "rb"))

    def swaps(self, text, pid="passage"):
        """Every resolved arm-b swap with its p50 score (before the threshold)."""
        from . import learned_words_r9 as R
        from . import learned_words_r12 as P12
        from . import learned_words_r21 as Q
        from . import learned_words_stacker as S

        variants, _ = R.word_swaps_two(text, self.model, pid, self.sn)
        got, rows = [], []
        for x in variants["all"]:
            r = S.swap_row(self.model, self.simpler, x)
            if r is not None:
                got.append(x)
                rows.append(r)
        if not got:
            return []
        X = Q.P13._x31(self.T, self.ids, got, rows)
        for x, r, sc in zip(got, rows, self.clf_s.predict_proba(X)[:, 1]):
            x.update(margin=r["f"]["margin"], stack=float(sc))
        a = [x for x in got if x["margin"] >= S.MIN_MARGIN]
        for x, sc in zip(a, P12.score_p(self.p50, a)):
            x["sc_p50"] = float(sc)
        return a

    def choose(self, swaps):
        from .learned_words_apply import choose

        return choose([x for x in swaps if x["sc_p50"] >= self.threshold])

    def rewrite(self, text, pid="passage"):
        chosen = self.choose(self.swaps(text, pid))
        return splice(text, chosen), [edit_record(x) for x in chosen]


def splice(text, chosen):
    """Replace each chosen swap's sentence in place (original spacing kept)."""
    from . import learned_words_r21 as Q
    from .learned_splits import sent

    if not chosen:
        return text
    by_sentence = {x["sentence"]: x for x in chosen}
    out, pos = [], 0
    for i, s in enumerate(sent(text)):
        start = text.index(s, pos)
        out.append(text[pos:start])
        if i in by_sentence:
            if by_sentence[i]["before"] != s:
                raise ValueError("swap sentence does not match the passage")
            out.append(Q.realized(by_sentence[i]))
        else:
            out.append(s)
        pos = start + len(s)
    out.append(text[pos:])
    return "".join(out)


def edit_record(x):
    return {"op": "word_p50", "sentence": x["sentence"], "word": x["word"], "rep": x["rep"],
            "score": round(x["sc_p50"], 4)}


class DefaultAfterF2:
    """Stages 2 and 3 of the default pipeline, applied to F2's output."""

    def __init__(self, state, threads=4):
        from cleartext.structure_v2 import StructureV2

        nli = SV.SmallNLI(Path(state) / "small-nli.jsonl")
        self.structure = StructureV2(ops=STRUCTURE_OPS, entailment=nli, min_entailment=MIN_ENTAILMENT)
        self.words = WordsP50(threads)

    def __call__(self, f2_output, pid="passage"):
        text, s_edits = self.structure.rewrite(f2_output)
        text, w_edits = self.words.rewrite(text, pid)
        return text, {"structure": s_edits, "words": w_edits}


def _load(path):
    return json.loads(Path(path).read_text()) if Path(path).exists() else {}


def run_run(args):
    state = SV.outside_checkout(args.state)
    inputs = json.loads(Path(args.f2).read_text())
    out_path = SV.outside_checkout(args.out)
    rows = _load(out_path)
    stage = DefaultAfterF2(state, args.threads)
    deadline = time.monotonic() + args.max_seconds
    for pid, f2 in inputs.items():
        if pid in rows:
            continue
        if time.monotonic() > deadline:
            break
        text, edits = stage(f2, pid)
        rows[pid] = {"f2": f2, "output": text, "edits": edits}
        SV.write_json(out_path, rows)
    print("COMPLETE" if len(rows) == len(inputs) else f"PARTIAL {len(inputs) - len(rows)} left", flush=True)


def run_dev(args):
    """`default` = F2 -> KEPT_V3 (0.5 floor) -> p50; `f2_words` = F2 -> p50, for attribution.
    The KEPT_V3 outputs are structure_v2's `combo-v3` dev arm, copied into --state."""
    state = SV.outside_checkout(args.state)
    dev, f2 = SV.f2_dev_outputs()  # refuses locked test IDs
    combo = json.loads((state / "dev-combo-v3.json").read_text())
    memo_path = state / "words-memo.json"
    memo = _load(memo_path)
    words = None
    deadline = time.monotonic() + args.max_seconds
    todo = []
    for p in dev:
        todo += [f2[p["id"]], combo[p["id"]]["output"]]
    for text in dict.fromkeys(todo):
        if text in memo:
            continue
        if time.monotonic() > deadline:
            print(f"PARTIAL {len(set(todo) - set(memo))} inputs left", flush=True)
            return
        words = words or WordsP50(args.threads)
        out, edits = words.rewrite(text)
        memo[text] = {"output": out, "edits": edits}
        SV.write_json(memo_path, memo)
        print(f"{time.strftime('%H:%M:%S')} {len(memo)} done, swaps={len(edits)}", flush=True)
    arms = {"f2_words": {}, "default": {}}
    for p in dev:
        a, b = f2[p["id"]], combo[p["id"]]["output"]
        arms["f2_words"][p["id"]] = {"output": memo[a]["output"], "edits": memo[a]["edits"]}
        arms["default"][p["id"]] = {"output": memo[b]["output"],
                                    "edits": combo[p["id"]]["edits"] + memo[b]["edits"]}
    for name, rows in arms.items():
        SV.write_json(state / f"dev-{name}.json", rows)
        changed = sum(rows[p["id"]]["output"] != f2[p["id"]] for p in dev)
        print(f"{name}: {changed} of {len(dev)} passages changed vs F2", flush=True)
    print("COMPLETE", flush=True)


def run_check(args):
    """Round 26's recorded p50 picks must be reproduced on --n of its passages."""
    from . import learned_words_r12 as P12
    from . import learned_words_r26 as R26
    from . import learned_words_stacker as S
    from .learned_words_apply import choose

    words = WordsP50(args.threads)
    panel = {p["id"]: p for p in json.load(open(R26.PANEL))}
    recs = [r for r in read_jsonl(R26.APPLY) if r["pid"] in panel]
    # Prefer passages where round 26 kept a p50 swap, then the rest, in file order.
    def recorded(rec):
        a = [s for s in rec["all"] if s["margin"] >= S.MIN_MARGIN]
        for s, x in zip(a, P12.score_p(words.p50, a)):
            s["sc_p50"] = float(x)
        return {(s["sentence"], s["word"], s["rep"]) for s in choose([s for s in a if s["sc_p50"] >= words.threshold])}

    recs.sort(key=lambda r: not recorded(r))
    results = []
    for rec in recs[: args.n]:
        want = recorded(rec)
        got = {(x["sentence"], x["word"], x["rep"]) for x in words.choose(words.swaps(panel[rec["pid"]]["original"], rec["pid"]))}
        results.append({"pid": rec["pid"], "recorded": sorted(map(list, want)), "recomputed": sorted(map(list, got)),
                        "match": want == got})
        print(rec["pid"], "match" if want == got else f"DIFF {want} vs {got}", flush=True)
    out = SV.outside_checkout(args.state) / "check-r26.json"
    SV.write_json(out, results)
    print(f"{sum(r['match'] for r in results)}/{len(results)} passages reproduce round 26's p50 picks")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("run", "dev", "check"):
        p = sub.add_parser(name)
        p.add_argument("--state", type=Path, required=True)
        p.add_argument("--threads", type=int, default=4)
        p.add_argument("--max-seconds", type=float, default=1500)
        if name == "run":
            p.add_argument("--f2", type=Path, required=True)
            p.add_argument("--out", type=Path, required=True)
        if name == "check":
            p.add_argument("--n", type=int, default=6)
    args = ap.parse_args(argv)
    {"run": run_run, "dev": run_dev, "check": run_check}[args.cmd](args)


if __name__ == "__main__":
    main()
