"""Build a text-review checklist from a predictions file (Yoga-side tool).

Reads model outputs the benchmark evidence does not store, scores the
cheap deterministic signals (explicit checks, TF-IDF, readability, all
from evals/, no embedding/NLI models needed), merges the stored
benchmark signals for known ids, and writes review_checklist.md.

Usage (from repo root, evals venv):
  python evals/reports/week7/score_predictions.py \
      --predictions predictions.jsonl --originals originals.json \
      --out evals/reports/week7/review_checklist.md

predictions.jsonl: one {"id": ..., "system": ..., "output": ...} per line.
originals.json: {"id": "original text", ...}. For the authored-smoke ids,
pass evals/data/week7_passages.json (list of {"id","original"}) instead.
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent.parent))

from evals.preservation import explicit_checks, tfidf_cosine_similarity  # noqa: E402
from evals.readability import readability_report  # noqa: E402

CHECKS = ("numbers_preserved", "dates_preserved", "entities_preserved",
          "negations_preserved", "tenses_preserved")


def load_originals(path):
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if isinstance(data, list):
        return {p["id"]: p["original"] for p in data}
    return data


def stored_signals():
    flags_path = Path(__file__).resolve().parent / "evidence_error_flags.json"
    if not flags_path.exists():
        return {}
    out = {}
    for f in json.loads(flags_path.read_text())["flags"]:
        out.setdefault(f["id"], []).append(f)
    return out


def main():
    ap = argparse.ArgumentParser(description="Build a text-review checklist.")
    ap.add_argument("--predictions", required=True)
    ap.add_argument("--originals", required=True)
    ap.add_argument("--out", default="evals/reports/week7/review_checklist.md")
    args = ap.parse_args()

    originals = load_originals(args.originals)
    signals = stored_signals()
    rows = []
    for line in Path(args.predictions).read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        pred = json.loads(line)
        pid, system, output = pred["id"], pred["system"], pred["output"]
        original = originals.get(pid)
        if original is None:
            print(f"skip {pid}: no original text", file=sys.stderr)
            continue
        checks = explicit_checks(original, output)
        failed = [k for k in CHECKS if checks.get(k) is not None and checks[k] < 1.0]
        read = readability_report(output)
        stored = "; ".join(
            f"{s['system']} fwd={s['nli_forward']:.3f} bwd={s['nli_backward']:.3f} "
            f"failed={','.join(s['failed_checks']) or 'none'}"
            for s in signals.get(pid, [])) or "none stored"
        rows.append({
            "id": pid, "system": system, "original": original, "output": output,
            "changed": output != original,
            "tfidf": round(tfidf_cosine_similarity(original, output), 3),
            "fkgl": round(read["flesch_kincaid_grade"], 2),
            "failed": failed, "stored": stored,
        })

    lines = ["# Text-review checklist", "",
             "Generated by score_predictions.py. Read each original/output "
             "pair, answer the packet questions, and code E0-E6.", ""]
    for r in rows:
        lines += [f"## {r['id']} ({r['system']})", "",
                  f"Changed: {r['changed']}; TF-IDF {r['tfidf']}; "
                  f"FKGL {r['fkgl']}; failed checks: "
                  f"{', '.join(r['failed']) or 'none'}",
                  f"Stored benchmark signals: {r['stored']}", "",
                  f"Original: {r['original']}", "",
                  f"Output: {r['output']}", "",
                  "Code (E0-E6): ___   Lost/altered detail: ___", ""]
    Path(args.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {args.out} ({len(rows)} predictions)")


if __name__ == "__main__":
    main()
