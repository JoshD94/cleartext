#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { analyze, body, decodeUtf8, langOf, loadTypescript, pyBatch } from './lex.mjs';

const USAGE = `usage: check.mjs --all | --changed [BASE] | --files LIST [--json] [--root DIR]

Fails on source comments. --all checks every tracked and untracked file; --changed checks only
lines added since the merge base with BASE (default: "base" in .comment-check.json, else
origin/main), including uncommitted and untracked files. --files checks whole files named in LIST
(one path per line, relative to --root or the current directory; a leading "-" marks a deletion and is
ignored) with --all's skips, legacy included, and needs no Git: for copies without .git, such as queue and
CI checkouts.

Allowed: shebangs, licenses, tool directives (eslint-disable, @ts-expect-error, deno-lint-ignore,
noqa, # type:, //go:, swiftlint: ...), JSDoc that tools read (types in JS, @deprecated ...), a
comment that is the only content of an empty block, and a rare business-decision exception whose
text starts with "Why:". Generated, vendored and fixture files are skipped, and so are
migrations in --all mode. Repo settings in .comment-check.json: "exclude" (globs never checked),
"legacy" (globs skipped by --all only: applied data fixes, files to clean later), "protectJsdoc" (every /** */ doc comment passes; for repos whose tooling reads them), "markers"
(regexes for comments a script reads), "typescript" (folders holding node_modules/typescript),
"base" (default origin/main).`;

const MARKER = /^Why:/;
const GENERATED_PATH = /(^|\/)(node_modules|dist|build|out|\.next|\.nuxt|\.svelte-kit|vendor|vendors|third_party|third-party|generated|__generated__|coverage|Pods|\.gradle|\.venv|venv|site-packages|DerivedData|fixtures?|__fixtures__|testdata|test-data|__snapshots__)(\/|$)|\.min\.[a-z]+$|\.d\.ts$|database\.types\.ts$|supabase\.types|types\/supabase|_pb2\.pyi?$|\.pb\.go$|\.g\.dart$|(^|\/)gradlew(\.bat)?$/;
const GENERATED_HEAD = /@generated|DO NOT EDIT|auto-?generated|generated by|Code generated/i;
const MIGRATION_PATH = /(^|\/)(migrations?|rollbacks?|alembic|db\/migrate)(\/|$)/i;

function globToRe(g) {
  let p = g.trim(); const dirOnly = p.endsWith('/'); if (dirOnly) p = p.replace(/\/+$/, '');
  const anchored = p.includes('/'); p = p.replace(/^\/+/, '');
  let re = '';
  for (let i = 0; i < p.length; i++) {
    const c = p[i];
    if (c === '*') {
      if (p[i + 1] === '*') { i++; if (p[i + 1] === '/') { i++; re += '(?:.*/)?'; } else re += '.*'; } else re += '[^/]*';
    } else if (c === '?') re += '[^/]';
    else re += c.replace(/[.+^${}()|[\]\\]/g, '\\$&');
  }
  return new RegExp((anchored ? '^' : '(^|/)') + re + (dirOnly ? '/.*$' : '(/.*)?$'));
}

function parseArgs(argv) {
  const o = { mode: null, base: null, json: false, root: null, list: null };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--all') o.mode = 'all';
    else if (a === '--changed') { o.mode = 'changed'; if (argv[i + 1] && !argv[i + 1].startsWith('-')) o.base = argv[++i]; }
    else if (a === '--files') { o.mode = 'files'; o.list = argv[++i]; if (!o.list) { console.error(`comment-check: --files needs a list\n${USAGE}`); process.exit(2); } }
    else if (a === '--json') o.json = true;
    else if (a === '--root') o.root = argv[++i];
    else if (a === '-h' || a === '--help') { console.log(USAGE); process.exit(0); }
    else { console.error(`comment-check: unknown argument ${a}\n${USAGE}`); process.exit(2); }
  }
  if (!o.mode) { console.error(USAGE); process.exit(2); }
  return o;
}

function unquote(q) {
  const bytes = []; const t = q.slice(1, -1);
  const esc = { n: 10, t: 9, r: 13, '"': 34, '\\': 92, a: 7, b: 8, f: 12, v: 11 };
  for (let i = 0; i < t.length; i++) {
    if (t[i] !== '\\') { bytes.push(...Buffer.from(t[i])); continue; }
    const m = /^[0-7]{3}/.exec(t.slice(i + 1));
    if (m) { bytes.push(parseInt(m[0], 8)); i += 3; } else { bytes.push(esc[t[i + 1]] ?? t.charCodeAt(i + 1)); i++; }
  }
  return Buffer.from(bytes).toString('utf8');
}

const git = (root, args) => execFileSync('git', ['-C', root, ...args], { maxBuffer: 1 << 30 }).toString();
const nulList = (s) => s.split('\0').filter(Boolean);

function addedLines(root, base) {
  let mb;
  try { mb = git(root, ['merge-base', base, 'HEAD']).trim(); } catch { throw new Error(`no merge base with ${base}; fetch it or pass --changed <base>`); }
  const added = new Map();
  let file = null, header = false;
  for (const raw of git(root, ['diff', '-U0', '--no-color', '--no-ext-diff', '--no-renames', '--src-prefix=a/', '--dst-prefix=b/', '--diff-filter=AM', mb, '--']).split('\n')) {
    if (raw.startsWith('diff --git ')) { header = true; file = null; continue; }
    const line = header && raw.startsWith('+++ ') ? raw.replace(/\t$/, '') : raw;
    if (header && line.startsWith('+++ ')) { file = line === '+++ /dev/null' ? null : line.startsWith('+++ "') ? unquote(line.slice(4)).slice(2) : line.slice(6); if (file && !added.has(file)) added.set(file, new Set()); continue; }
    const h = /^@@ -\S+ \+(\d+)(?:,(\d+))? @@/.exec(line);
    if (h) header = false;
    if (h && file) { const start = +h[1], count = h[2] == null ? 1 : +h[2]; for (let k = 0; k < count; k++) added.get(file).add(start + k); }
  }
  for (const f of nulList(git(root, ['ls-files', '-z', '--others', '--exclude-standard']))) added.set(f, 'all');
  return added;
}

export function check({ root, mode, base, cfg = {}, list = [] }) {
  const excludes = (cfg.exclude || []).map(globToRe);
  const legacy = (cfg.legacy || []).map(globToRe);
  let files, added = null;
  if (mode === 'changed') { added = addedLines(root, base); files = [...added.keys()]; }
  else if (mode === 'files') files = list.map((l) => l.trim()).filter((l) => l && !l.startsWith('-')).map((l) => l.replace(/^\.\//, ''));
  else files = [...nulList(git(root, ['ls-files', '-z'])), ...nulList(git(root, ['ls-files', '-z', '--others', '--exclude-standard']))];
  const todo = []; const skipped = {}; const partial = [];
  const skip = (why) => { skipped[why] = (skipped[why] || 0) + 1; };
  for (const f of [...new Set(files)].sort()) {
    if (GENERATED_PATH.test(f) || excludes.some((re) => re.test(f))) continue;
    if (mode !== 'changed' && (MIGRATION_PATH.test(f) || legacy.some((re) => re.test(f)))) continue;
    const full = path.join(root, f);
    let src;
    try { const st = fs.lstatSync(full); if (!st.isFile() || st.size > 800_000) continue; src = decodeUtf8(fs.readFileSync(full)); } catch { continue; }
    if (src == null) continue;
    const lang = langOf(f, src); if (!lang) continue;
    if (GENERATED_HEAD.test(src.slice(0, 600))) continue;
    if (src.split('\n', 5).some((l) => l.length > 2000)) continue;
    todo.push({ f, src, lang });
  }
  if (todo.some((t) => t.lang === 'ts') && !loadTypescript([root, ...(cfg.typescript || []).map((d) => path.join(root, d))])) {
    throw new Error('typescript is not installed; run npm ci, or list a folder holding node_modules/typescript under "typescript" in .comment-check.json');
  }
  const py = pyBatch(todo.filter((t) => t.lang === 'py').map((t) => ({ key: t.f, src: t.src })));
  const findings = [];
  for (const { f, src, lang } of todo) {
    const A = analyze(f, src, lang, py.get(f), { markers: cfg.markers || [], protectJsdoc: !!cfg.protectJsdoc });
    if (!A.ok) { skip('could not lex'); partial.push(f); continue; }
    if (A.partial) partial.push(f);
    const lines = added && added.get(f);
    for (const b of A.blocks) {
      if (b.protect) continue;
      if (MARKER.test(body(b.text, b.kind))) continue;
      if (lines && lines !== 'all') { let hit = false; for (let l = b.start; l <= b.end && !hit; l++) hit = lines.has(l); if (!hit) continue; }
      findings.push({ file: f, line: b.start, col: b.col + 1, endLine: b.end, text: b.text });
    }
  }
  return { findings, files: todo.length, skipped, partial };
}

function main() {
  const o = parseArgs(process.argv.slice(2));
  let root;
  if (o.root) root = path.resolve(o.root);
  else if (o.mode === 'files') root = process.cwd();
  else try { root = git(process.cwd(), ['rev-parse', '--show-toplevel']).trim(); } catch { console.error('comment-check: not inside a Git checkout'); process.exit(2); }
  let list = [];
  if (o.mode === 'files') { try { list = fs.readFileSync(path.resolve(o.list), 'utf8').split('\n'); } catch { console.error(`comment-check: cannot read ${o.list}`); process.exit(2); } }
  let cfg = {};
  const cfgPath = path.join(root, '.comment-check.json');
  if (fs.existsSync(cfgPath)) cfg = JSON.parse(fs.readFileSync(cfgPath, 'utf8'));
  const base = o.base || cfg.base || 'origin/main';
  let r;
  try { r = check({ root, mode: o.mode, base, cfg, list }); } catch (e) { console.error(`comment-check: ${e.message}`); process.exit(2); }
  if (o.json) { console.log(JSON.stringify(r, null, 1)); process.exit(r.findings.length ? 1 : 0); }
  for (const x of r.findings) {
    const first = x.text.split('\n')[0].trim();
    console.log(`${x.file}:${x.line}:${x.col}: ${first.length > 110 ? first.slice(0, 107) + '...' : first}${x.endLine > x.line ? ` (+${x.endLine - x.line} lines)` : ''}`);
  }
  if (r.partial.length) console.log(`comment-check: ${r.partial.length} files only partly checked (the scanner stopped at a construct it cannot follow): ${r.partial.slice(0, 20).join(', ')}${r.partial.length > 20 ? ', ...' : ''}`);
  const scope = o.mode === 'all' ? 'all files' : o.mode === 'files' ? `files in ${o.list}` : `lines added since ${base}`;
  const extra = Object.entries(r.skipped).map(([k, v]) => `${v} ${k}`).join(', ');
  if (r.findings.length) {
    const nFiles = new Set(r.findings.map((x) => x.file)).size;
    console.log(`comment-check FAIL: ${r.findings.length} comments in ${nFiles} files (${scope}${extra ? '; skipped ' + extra : ''}). Remove them; a rare weird business decision may stay as a comment starting with "Why:".`);
    process.exit(1);
  }
  console.log(`comment-check PASS: ${r.files} files, no comments (${scope}${extra ? '; skipped ' + extra : ''})`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) main();
